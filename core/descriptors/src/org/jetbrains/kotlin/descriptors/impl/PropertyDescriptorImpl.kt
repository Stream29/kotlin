// Translated-unverified.
open class PropertyDescriptorImpl protected constructor(
    containingDeclaration: DeclarationDescriptor, original: PropertyDescriptor?, annotations: Annotations,
    modality: Modality, visibility: DescriptorVisibility, isVar: Boolean, name: Name, kind: Kind, source: SourceElement,
    private val lateInit: Boolean, isConst: Boolean, isExpect: Boolean, isActual: Boolean, isExternal: Boolean, isDelegated: Boolean
) : VariableDescriptorWithInitializerImpl(containingDeclaration, annotations, name, null, isVar, source), PropertyDescriptor {
    private val propertyModality = modality
    private var propertyVisibility = visibility
    private var overriddenProperties: Collection<PropertyDescriptor>? = null
    private val originalDescriptor = original ?: this
    private val memberKind = kind
    private val constFlag = isConst
    private val expectFlag = isExpect
    private val actualFlag = isActual
    private val externalFlag = isExternal
    private val delegatedFlag = isDelegated
    private var contextReceiverParameters: List<ReceiverParameterDescriptor> = emptyList()
    private var dispatchReceiverParameter: ReceiverParameterDescriptor? = null
    private var extensionReceiverParameter: ReceiverParameterDescriptor? = null
    private var typeParameters: List<TypeParameterDescriptor>? = null
    private var propertyGetter: PropertyGetterDescriptorImpl? = null
    private var propertySetter: PropertySetterDescriptor? = null
    private var setterProjectedOut = false
    private var backingField: FieldDescriptor? = null
    private var delegateField: FieldDescriptor? = null
    // Upstream intentionally does nothing: the corresponding setter is generated by default.
    open fun setInType(inType: KotlinType) {}
    override fun getInType(): KotlinType? = propertySetter?.getValueParameters()?.get(0)?.getType()
    @Deprecated("This method is left for binary compatibility with android.nav.safearg plugin. Used in SafeArgSyntheticDescriptorGenerator.kt")
    open fun setType(outType: KotlinType, typeParameters: List<TypeParameterDescriptor>,
                     dispatchReceiverParameter: ReceiverParameterDescriptor?, extensionReceiverParameter: ReceiverParameterDescriptor?) {
        setType(outType, typeParameters, dispatchReceiverParameter, extensionReceiverParameter, emptyList())
    }
    open fun setType(outType: KotlinType, typeParameters: List<TypeParameterDescriptor>,
                     dispatchReceiverParameter: ReceiverParameterDescriptor?, extensionReceiverParameter: ReceiverParameterDescriptor?,
                     contextReceiverParameters: List<ReceiverParameterDescriptor>) {
        setOutType(outType)
        this.typeParameters = ArrayList(typeParameters)
        this.extensionReceiverParameter = extensionReceiverParameter
        this.dispatchReceiverParameter = dispatchReceiverParameter
        this.contextReceiverParameters = contextReceiverParameters
    }
    open fun initialize(getter: PropertyGetterDescriptorImpl?, setter: PropertySetterDescriptor?) {
        initialize(getter, setter, null, null)
    }
    open fun initialize(getter: PropertyGetterDescriptorImpl?, setter: PropertySetterDescriptor?,
                        backingField: FieldDescriptor?, delegateField: FieldDescriptor?) {
        propertyGetter = getter
        propertySetter = setter
        this.backingField = backingField
        this.delegateField = delegateField
    }
    open fun setSetterProjectedOut(setterProjectedOut: Boolean) { this.setterProjectedOut = setterProjectedOut }
    open fun setVisibility(visibility: DescriptorVisibility) { propertyVisibility = visibility }
    override fun getTypeParameters(): List<TypeParameterDescriptor> =
        typeParameters ?: throw IllegalStateException("typeParameters == null for $this")
    override fun validate() { getTypeParameters() }
    override fun getContextReceiverParameters(): List<ReceiverParameterDescriptor> = contextReceiverParameters
    override fun getExtensionReceiverParameter(): ReceiverParameterDescriptor? = extensionReceiverParameter
    override fun getDispatchReceiverParameter(): ReceiverParameterDescriptor? = dispatchReceiverParameter
    override fun getReturnType(): KotlinType = getType()
    override fun getModality(): Modality = propertyModality
    override fun getVisibility(): DescriptorVisibility = propertyVisibility
    override fun getGetter(): PropertyGetterDescriptorImpl? = propertyGetter
    override val getter: PropertyGetterDescriptorImpl? get() = getGetter()
    override fun getSetter(): PropertySetterDescriptor? = propertySetter
    override fun isSetterProjectedOut(): Boolean = setterProjectedOut
    override fun isLateInit(): Boolean = lateInit
    override fun isConst(): Boolean = constFlag
    override fun isExternal(): Boolean = externalFlag
    override val isDelegated: Boolean get() = delegatedFlag
    override fun getAccessors(): List<PropertyAccessorDescriptor> {
        val result = ArrayList<PropertyAccessorDescriptor>(2)
        propertyGetter?.let { result.add(it) }
        propertySetter?.let { result.add(it) }
        return result
    }
    override fun substitute(substitutor: TypeSubstitutor): PropertyDescriptor? {
        if (substitutor.isEmpty()) return this
        return newCopyBuilder().setSubstitution(substitutor.getSubstitution()).setOriginal(getOriginal()).build()
    }

    open inner class CopyConfiguration : CallableMemberDescriptor.CopyBuilder<PropertyDescriptor> {
        var owner: DeclarationDescriptor = getContainingDeclaration()
        var modality: Modality = getModality()
        var visibility: DescriptorVisibility = getVisibility()
        var original: PropertyDescriptor? = null
        var preserveSourceElement = false
        var kind: Kind = getKind()
        var substitution: TypeSubstitution = TypeSubstitution.EMPTY
        var copyOverrides = true
        var dispatchReceiverParameter = this@PropertyDescriptorImpl.dispatchReceiverParameter
        var newTypeParameters: List<TypeParameterDescriptor>? = null
        var name: Name = getName()
        var returnType: KotlinType = getType()
        override fun setOwner(owner: DeclarationDescriptor): CopyConfiguration { this.owner = owner; return this }
        override fun setOriginal(original: CallableMemberDescriptor?): CopyConfiguration { this.original = original as PropertyDescriptor?; return this }
        override fun setPreserveSourceElement(): CopyConfiguration { preserveSourceElement = true; return this }
        override fun setReturnType(type: KotlinType): CallableMemberDescriptor.CopyBuilder<PropertyDescriptor> { returnType = type; return this }
        override fun setModality(modality: Modality): CopyConfiguration { this.modality = modality; return this }
        override fun setVisibility(visibility: DescriptorVisibility): CopyConfiguration { this.visibility = visibility; return this }
        override fun setKind(kind: Kind): CopyConfiguration { this.kind = kind; return this }
        override fun setTypeParameters(parameters: List<TypeParameterDescriptor>): CallableMemberDescriptor.CopyBuilder<PropertyDescriptor> {
            newTypeParameters = parameters
            return this
        }
        override fun setDispatchReceiverParameter(dispatchReceiverParameter: ReceiverParameterDescriptor?): CopyConfiguration {
            this.dispatchReceiverParameter = dispatchReceiverParameter
            return this
        }
        override fun setSubstitution(substitution: TypeSubstitution): CopyConfiguration { this.substitution = substitution; return this }
        override fun setCopyOverrides(copyOverrides: Boolean): CopyConfiguration { this.copyOverrides = copyOverrides; return this }
        override fun setName(name: Name): CallableMemberDescriptor.CopyBuilder<PropertyDescriptor> { this.name = name; return this }
        override fun build(): PropertyDescriptor? = doSubstitute(this)
        internal fun getOriginalGetter(): PropertyGetterDescriptor? = original?.getGetter()
        internal fun getOriginalSetter(): PropertySetterDescriptor? = original?.getSetter()
    }
    override fun newCopyBuilder(): CopyConfiguration = CopyConfiguration()
    private fun getSourceToUseForCopy(preserveSource: Boolean, original: PropertyDescriptor?): SourceElement =
        if (preserveSource) (original ?: getOriginal()).getSource() else SourceElement.NO_SOURCE
    protected open fun doSubstitute(copyConfiguration: CopyConfiguration): PropertyDescriptor? {
        val substitutedDescriptor = createSubstitutedCopy(
            copyConfiguration.owner, copyConfiguration.modality, copyConfiguration.visibility,
            copyConfiguration.original, copyConfiguration.kind, copyConfiguration.name,
            getSourceToUseForCopy(copyConfiguration.preserveSourceElement, copyConfiguration.original)
        )
        val originalTypeParameters = copyConfiguration.newTypeParameters ?: getTypeParameters()
        val substitutedTypeParameters = ArrayList<TypeParameterDescriptor>(originalTypeParameters.size)
        val substitutor = DescriptorSubstitutor.substituteTypeParameters(
            originalTypeParameters, copyConfiguration.substitution, substitutedDescriptor, substitutedTypeParameters
        )
        val originalOutType = copyConfiguration.returnType
        val outType = substitutor.substitute(originalOutType, Variance.OUT_VARIANCE) ?: return null
        val inType = substitutor.substitute(originalOutType, Variance.IN_VARIANCE)
        if (inType != null) substitutedDescriptor.setInType(inType)
        val dispatchReceiver = copyConfiguration.dispatchReceiverParameter
        val substitutedDispatchReceiver = if (dispatchReceiver != null) dispatchReceiver.substitute(substitutor) ?: return null else null
        val substitutedExtensionReceiver = extensionReceiverParameter?.let { substituteParameterDescriptor(substitutor, substitutedDescriptor, it) }
        val substitutedContextReceivers = ArrayList<ReceiverParameterDescriptor>()
        for (contextReceiver in contextReceiverParameters) {
            val substituted = substituteContextParameterDescriptor(substitutor, substitutedDescriptor, contextReceiver)
            if (substituted != null) substitutedContextReceivers.add(substituted)
        }
        substitutedDescriptor.setType(outType, substitutedTypeParameters, substitutedDispatchReceiver, substitutedExtensionReceiver, substitutedContextReceivers)
        val getter = propertyGetter
        val newGetter = getter?.let {
            PropertyGetterDescriptorImpl(substitutedDescriptor, it.annotations, copyConfiguration.modality,
                normalizeVisibility(it.getVisibility(), copyConfiguration.kind), it.isDefault(), it.isExternal(), it.isInline(),
                copyConfiguration.kind, copyConfiguration.getOriginalGetter(), SourceElement.NO_SOURCE)
        }
        if (newGetter != null) {
            val returnType = getter!!.getReturnType()
            newGetter.setInitialSignatureDescriptor(getSubstitutedInitialSignatureDescriptor(substitutor, getter))
            newGetter.initialize(returnType?.let { substitutor.substitute(it, Variance.OUT_VARIANCE) })
        }
        val setter = propertySetter
        val newSetter = setter?.let {
            PropertySetterDescriptorImpl(substitutedDescriptor, it.annotations, copyConfiguration.modality,
                normalizeVisibility(it.getVisibility(), copyConfiguration.kind), it.isDefault(), it.isExternal(), it.isInline(),
                copyConfiguration.kind, copyConfiguration.getOriginalSetter(), SourceElement.NO_SOURCE)
        }
        if (newSetter != null) {
            var substitutedValueParameters = FunctionDescriptorImpl.getSubstitutedValueParameters(
                newSetter, setter!!.getValueParameters(), substitutor, false, false, null
            )
            if (substitutedValueParameters == null) {
                // A var projected to out cannot be assigned, but its getter remains usable.
                substitutedDescriptor.setSetterProjectedOut(true)
                substitutedValueParameters = listOf(PropertySetterDescriptorImpl.createSetterParameter(
                    newSetter, copyConfiguration.owner.builtIns.getNothingType(), setter.getValueParameters()[0].annotations
                ))
            }
            if (substitutedValueParameters.size != 1) throw IllegalStateException()
            newSetter.setInitialSignatureDescriptor(getSubstitutedInitialSignatureDescriptor(substitutor, setter))
            newSetter.initialize(substitutedValueParameters[0])
        }
        substitutedDescriptor.initialize(
            newGetter, newSetter, backingField?.let { FieldDescriptorImpl(it.annotations, substitutedDescriptor) },
            delegateField?.let { FieldDescriptorImpl(it.annotations, substitutedDescriptor) }
        )
        if (copyConfiguration.copyOverrides) {
            val overridden = SmartSet.create<CallableMemberDescriptor>()
            for (property in getOverriddenDescriptors()) overridden.add(property.substitute(substitutor)!!)
            substitutedDescriptor.setOverriddenDescriptors(overridden)
        }
        if (isConst() && compileTimeInitializerFactory != null)
            substitutedDescriptor.setCompileTimeInitializer(compileTimeInitializer, compileTimeInitializerFactory!!)
        return substitutedDescriptor
    }
    protected open fun createSubstitutedCopy(
        newOwner: DeclarationDescriptor, newModality: Modality, newVisibility: DescriptorVisibility, original: PropertyDescriptor?,
        kind: Kind, newName: Name, source: SourceElement
    ): PropertyDescriptorImpl = PropertyDescriptorImpl(newOwner, original, annotations, newModality, newVisibility, isVar(), newName, kind,
        source, isLateInit(), isConst(), isExpect(), isActual(), isExternal(), isDelegated)
    override fun <R, D> accept(visitor: DeclarationDescriptorVisitor<R, D>, data: D): R? = visitor.visitPropertyDescriptor(this, data)
    override fun getOriginal(): PropertyDescriptor = if (originalDescriptor === this) this else originalDescriptor.getOriginal()
    override fun getKind(): Kind = memberKind
    override fun isExpect(): Boolean = expectFlag
    override fun isActual(): Boolean = actualFlag
    override fun getBackingField(): FieldDescriptor? = backingField
    override fun getDelegateField(): FieldDescriptor? = delegateField
    @Suppress("UNCHECKED_CAST")
    override fun setOverriddenDescriptors(overriddenDescriptors: Collection<CallableMemberDescriptor?>) {
        overriddenProperties = overriddenDescriptors as Collection<PropertyDescriptor>
    }
    override fun getOverriddenDescriptors(): Collection<PropertyDescriptor> = overriddenProperties ?: emptyList()
    override fun copy(newOwner: DeclarationDescriptor, modality: Modality, visibility: DescriptorVisibility, kind: Kind, copyOverrides: Boolean): PropertyDescriptor =
        newCopyBuilder().setOwner(newOwner).setOriginal(null).setModality(modality).setVisibility(visibility).setKind(kind).setCopyOverrides(copyOverrides).build()!!
    override fun <V> getUserData(key: CallableDescriptor.UserDataKey<V>): V? = null
    companion object {
        fun create(
            containingDeclaration: DeclarationDescriptor, annotations: Annotations, modality: Modality, visibility: DescriptorVisibility,
            isVar: Boolean, name: Name, kind: Kind, source: SourceElement, lateInit: Boolean, isConst: Boolean,
            isExpect: Boolean, isActual: Boolean, isExternal: Boolean, isDelegated: Boolean
        ): PropertyDescriptorImpl =
            PropertyDescriptorImpl(containingDeclaration, null, annotations, modality, visibility, isVar, name, kind, source,
                                   lateInit, isConst, isExpect, isActual, isExternal, isDelegated)
        private fun normalizeVisibility(prev: DescriptorVisibility, kind: Kind): DescriptorVisibility =
            if (kind == Kind.FAKE_OVERRIDE && DescriptorVisibilities.isPrivate(prev.normalize())) DescriptorVisibilities.INVISIBLE_FAKE else prev
        private fun substituteParameterDescriptor(
            substitutor: TypeSubstitutor, substitutedPropertyDescriptor: PropertyDescriptor, receiverParameterDescriptor: ReceiverParameterDescriptor
        ): ReceiverParameterDescriptor? {
            val type = substitutor.substitute(receiverParameterDescriptor.getType(), Variance.IN_VARIANCE) ?: return null
            return ReceiverParameterDescriptorImpl(substitutedPropertyDescriptor,
                ExtensionReceiver(substitutedPropertyDescriptor, type, receiverParameterDescriptor.getValue()), receiverParameterDescriptor.annotations)
        }
        private fun substituteContextParameterDescriptor(
            substitutor: TypeSubstitutor, substitutedPropertyDescriptor: PropertyDescriptor, receiverParameterDescriptor: ReceiverParameterDescriptor
        ): ReceiverParameterDescriptor? {
            val type = substitutor.substitute(receiverParameterDescriptor.getType(), Variance.IN_VARIANCE) ?: return null
            return ReceiverParameterDescriptorImpl(substitutedPropertyDescriptor, ContextReceiver(substitutedPropertyDescriptor, type,
                (receiverParameterDescriptor.getValue() as ImplicitContextReceiver).customLabelName, receiverParameterDescriptor.getValue()), receiverParameterDescriptor.annotations)
        }
        private fun getSubstitutedInitialSignatureDescriptor(substitutor: TypeSubstitutor, accessorDescriptor: PropertyAccessorDescriptor): FunctionDescriptor? =
            accessorDescriptor.getInitialSignatureDescriptor()?.substitute(substitutor)
    }
}

var PropertyDescriptorImpl.visibility: DescriptorVisibility get() = getVisibility(); set(value) = setVisibility(value)
var PropertyDescriptorImpl.isSetterProjectedOut: Boolean get() = isSetterProjectedOut(); set(value) = setSetterProjectedOut(value)
